def main():
    voc = json.load(open(os.path.join(ROOT, 'data', 'vocab.json'), encoding='utf-8'))['vocab']
    # 词表里有些词按日常写法存成了假名（ここ/する/できる 这类 JMdict 标 uk 的词），
    # 所以校验要同时认汉字形和假名形，否则会误报缺词。
    forms = {v['jp'] for v in voc} | {v['kana'] for v in voc}

    lessons, missing = [], []
    for i, c in enumerate(COURSE, 1):
        for w in c['words']:
            if w not in forms:
                missing.append((i, w))
        lessons.append({
            'id': f'L{i:02d}', 'n': i, 'unit': c['unit'], 'title': c['title'],
            'src': c['src'], 'pattern': c['pattern'], 'explain': c['explain'],
            'examples': [{'jp': a, 'cn': b, 'note': d} for a, b, d in c['examples']],
            'words': c['words'], 'drill': c['drill'], 'gate': c['gate'],
        })

    units = []
    for l in lessons:
        if not units or units[-1]['name'] != l['unit']:
            units.append({'name': l['unit'], 'from': l['n'], 'to': l['n']})
        else:
            units[-1]['to'] = l['n']

    out = {'version': 1,
           'source': '语法点顺序照《みんなの日本語初級Ⅰ》第1-25课句型大纲；'
                     '假名与音读规律为本项目补充；词汇取自本项目 2000 词高频表',
           'units': units, 'lessons': lessons}
    path = os.path.join(ROOT, 'data', 'course.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, separators=(',', ':'))

    log(f'课程 {len(lessons)} 课，{len(units)} 个单元')
    for u in units:
        log(f"  {u['name']:6s} 第 {u['from']}-{u['to']} 课")
    log(f"例句 {sum(len(l['examples']) for l in lessons)} 条，"
        f"讲解正文 {sum(len(l['explain']) for l in lessons)} 字")
    if missing:
        log(f'!! {len(missing)} 个词不在 vocab.json（需补或改写）:')
        for n, w in missing[:20]:
            log(f'   第{n}课 {w}')
        sys.exit(1)
    log(f'-> {path}  {os.path.getsize(path)/1024:.0f} KB')


if __name__ == '__main__':
    main()
