import { writeFileSync, readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kanaData = JSON.parse(readFileSync(join(root, 'data', 'kana.json'), 'utf8'));

// 从 kana.json 建平/片假名 -> 罗马音映射（含拗音的两字组合）
const MAP = new Map();
for (const c of kanaData.cards) {
  MAP.set(c.hira, c.romaji);
  MAP.set(c.kata, c.romaji);
}
const VOWELS = new Set(['a', 'i', 'u', 'e', 'o']);

/** 假名 -> 罗马音（Hepburn 式，处理促音/长音/撥音） */
export function romanize(kana) {
  const out = [];
  let i = 0;
  while (i < kana.length) {
    const ch = kana[i];
    // 促音：下一个音节的首辅音加倍
    if (ch === 'っ' || ch === 'ッ') {
      const two = kana.slice(i + 1, i + 3);
      const nextR = MAP.get(two) || MAP.get(kana[i + 1]) || '';
      const m = /^[a-z]/.exec(nextR);
      if (m && !VOWELS.has(nextR[0])) out.push(nextR[0]);
      i++;
      continue;
    }
    // 片假名长音符：重复前一个元音
    if (ch === 'ー') {
      const prev = out[out.length - 1] || '';
      const lastVowel = [...prev].reverse().find((x) => VOWELS.has(x));
      if (lastVowel) out.push(lastVowel);
      i++;
      continue;
    }
    // 优先匹配两字（拗音 きゃ/しゅ/ちょ…）
    const two = kana.slice(i, i + 2);
    if (two.length === 2 && MAP.has(two)) {
      out.push(MAP.get(two));
      i += 2;
      continue;
    }
    if (MAP.has(ch)) {
      let r = MAP.get(ch);
      // 撥音 ん 后接元音或 y 时写 n'，避免 きんいろ 被读成 ki-ni-ro
      if (r === 'n') {
        const nx = kana.slice(i + 1, i + 3);
        const nr = MAP.get(nx) || MAP.get(kana[i + 1]) || '';
        if (nr && (VOWELS.has(nr[0]) || nr[0] === 'y')) r = "n'";
      }
      out.push(r);
      i++;
      continue;
    }
    // 长音点、中点等原样保留
    out.push(ch);
    i++;
  }
  return out.join('');
}

