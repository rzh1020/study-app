const rows = TSV.split('\n').map((l) => l.split('|'));
const vocab = [];
const seen = new Set();
const errs = [];
rows.forEach((r, idx) => {
  if (r.length !== 7) { errs.push(`第${idx + 1}行字段数=${r.length}（应 7）: ${r.join('|')}`); return; }
  const [jp, kana, cn, pos, stage, exJp, exCn] = r.map((x) => x.trim());
  if (!jp || !kana || !cn || !pos || !stage) { errs.push(`第${idx + 1}行有空字段: ${r.join('|')}`); return; }
  // 读音必须全是假名（否则说明汉字漏填到 kana 列）
  if (!/^[\u3040-\u309F\u30A0-\u30FFー]+$/.test(kana)) errs.push(`第${idx + 1}行读音含非假名字符: ${kana}`);
  const key = jp + '/' + kana;
  if (seen.has(key)) errs.push(`重复词条: ${key}`);
  seen.add(key);
  vocab.push({
    id: `v-${String(vocab.length + 1).padStart(3, '0')}`,
    jp, kana, romaji: romanize(kana), cn, pos, stage,
    exJp: exJp || '', exCn: exCn || '',
  });
});

// 转写器自检：这些是最容易出错的形态
const ROMAJI_CASES = [
  ['がっこう', 'gakkou'], ['きって', 'kitte'], ['ちょっと', 'chotto'],
  ['にほんご', 'nihongo'], ['しんじる', 'shinjiru'], ['つよい', 'tsuyoi'],
  ['コーヒー', 'koohii'], ['いっしょに', 'isshoni'], ['はずかしい', 'hazukashii'],
  ['だいじょうぶ', 'daijoubu'], ['きんいろ', "kin'iro"], ['おんがく', 'ongaku'],
  ['じゃない', 'janai'], ['ぜんぜん', 'zenzen'], ['やっぱり', 'yappari'],
];
let rFail = 0;
for (const [k, want] of ROMAJI_CASES) {
  const got = romanize(k);
  if (got !== want) { console.error(`  转写错: ${k} -> ${got}（期望 ${want}）`); rFail++; }
}

if (errs.length) { console.error('数据错误:\n' + errs.join('\n')); process.exit(1); }
if (rFail) { console.error(`转写器 ${rFail} 项不符`); process.exit(1); }

const byStage = {};
for (const v of vocab) byStage[v.stage] = (byStage[v.stage] || 0) + 1;
writeFileSync(join(root, 'data', 'vocab.json'), JSON.stringify({ version: 1, vocab }, null, 1), 'utf8');
console.log(`词条 ${vocab.length}`, byStage);
console.log(`有例句 ${vocab.filter((v) => v.exJp).length}`);
console.log(`转写自检 ${ROMAJI_CASES.length}/${ROMAJI_CASES.length} 通过`);
console.log('抽样:', vocab.slice(0, 3).map((v) => `${v.jp}(${v.romaji})`).join(' '));
console.log('OK -> data/vocab.json');
